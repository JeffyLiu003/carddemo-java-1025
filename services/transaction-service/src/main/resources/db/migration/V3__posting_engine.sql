-- A1.2 过账引擎：过账类型 / 过账规则 / 过账批次 / 过账分录
-- 契约见 docs/design/11-money-path-slice-a2.md §2.1–2.2

CREATE TABLE posting_type (
    type_code      VARCHAR(20) PRIMARY KEY,
    name           VARCHAR(50)  NOT NULL,
    description    VARCHAR(200),
    account_effect VARCHAR(10)  NOT NULL,
    active         BOOLEAN      NOT NULL DEFAULT TRUE,
    version        BIGINT       NOT NULL DEFAULT 0
);

CREATE TABLE posting_rule (
    rule_id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type_code           VARCHAR(20) NOT NULL,
    leg_no              INTEGER     NOT NULL,
    account_role        VARCHAR(30) NOT NULL,
    direction           VARCHAR(2)  NOT NULL,
    ledger_account_code VARCHAR(10) NOT NULL,
    description         VARCHAR(200),
    version             BIGINT      NOT NULL DEFAULT 0,
    CONSTRAINT uk_posting_rule_type_leg UNIQUE (type_code, leg_no),
    CONSTRAINT fk_posting_rule_type FOREIGN KEY (type_code) REFERENCES posting_type (type_code)
);

CREATE TABLE posting_batch (
    batch_id        VARCHAR(36) PRIMARY KEY,
    idempotency_key VARCHAR(80)   NOT NULL,
    type_code       VARCHAR(20)   NOT NULL,
    account_id      VARCHAR(11)   NOT NULL,
    amount          NUMERIC(12, 2) NOT NULL,
    currency        VARCHAR(3)    NOT NULL,
    description     VARCHAR(200),
    status          VARCHAR(10)   NOT NULL,
    reversal_of     VARCHAR(36),
    ledger_entry_id VARCHAR(64),
    created_at      TIMESTAMP     NOT NULL,
    reversed_at     TIMESTAMP,
    version         BIGINT        NOT NULL DEFAULT 0,
    CONSTRAINT uk_posting_batch_idempotency UNIQUE (idempotency_key)
);

-- 一个原批次最多一个冲正批次（冲正批次的幂等键为 reversal:<原批次号>）
CREATE UNIQUE INDEX uk_posting_batch_reversal_of ON posting_batch (reversal_of);
CREATE INDEX idx_posting_batch_account ON posting_batch (account_id);
CREATE INDEX idx_posting_batch_created ON posting_batch (created_at);

CREATE TABLE posting_leg (
    leg_id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id            VARCHAR(36)   NOT NULL,
    leg_no              INTEGER       NOT NULL,
    account_role        VARCHAR(30)   NOT NULL,
    direction           VARCHAR(2)    NOT NULL,
    ledger_account_code VARCHAR(10)   NOT NULL,
    amount              NUMERIC(12, 2) NOT NULL,
    created_at          TIMESTAMP     NOT NULL,
    CONSTRAINT uk_posting_leg_batch_leg UNIQUE (batch_id, leg_no),
    CONSTRAINT fk_posting_leg_batch FOREIGN KEY (batch_id) REFERENCES posting_batch (batch_id)
);

